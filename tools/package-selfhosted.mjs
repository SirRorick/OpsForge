// ---------------------------------------------------------------------------
// package-selfhosted.mjs — assemble the private, fully-loaded build
// ---------------------------------------------------------------------------
// Usage:
//   npm run package                  build reference/selfhosted/
//   npm run package -- --out DIR     somewhere else
//   npm run package -- --vendor-three  copy three.js in for offline use
//
// The public repository ships the editor with thumbnails and stand-in shapes.
// This assembles the other payload: the same editor with the game's own models
// beside it, laid out as a static site to sit behind Caddy.
//
// It is a copy, not a fork. Nothing here is built differently — `index.html` is
// the same single-file bundle `npm run build` writes to dist/, and the only
// reason this folder exists is that `assets/Prefabs` cannot go in the
// repository. So keeping the two in step is: build, stage, package.
//
// The output lands under reference/, which is gitignored, because every file it
// adds beyond the bundle is the game's artwork.
// ---------------------------------------------------------------------------

import {
  readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync, rmSync, cpSync,
} from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from '../build.mjs';
import { zipDirectory } from './zip.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const THREE_VERSION = '0.169.0';

const mb = (n) => `${(n / 1048576).toFixed(1)} MB`;

/**
 * Empty a directory without deleting the directory itself.
 *
 * Deleting the folder outright is the obvious thing and it is wrong here.
 * Anything holding the directory open — a static server run from inside it,
 * which is exactly what these folders are for — makes Windows refuse the
 * removal with EPERM, and it refuses it *after* having already deleted the
 * contents. That leaves the package folder empty and the run failed, which is
 * the worst of both. Removing the entries and keeping the directory never needs
 * the handle nobody will give up.
 */
function emptyDirectory(dir) {
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
    return;
  }
  for (const entry of readdirSync(dir)) {
    rmSync(join(dir, entry), { recursive: true, force: true });
  }
}

function dirSize(dir) {
  let total = 0, files = 0;
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else { total += statSync(p).size; files++; }
    }
  };
  if (existsSync(dir)) walk(dir);
  return { total, files };
}

