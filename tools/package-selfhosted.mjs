/**
 * Rewrite the bundle's import map to point at local copies.
 *
 * Only touched when vendoring: the default build keeps the CDN URLs, which is
 * what dist/ ships with and what the public build uses.
 */
function vendorThree(html, files) {
  const map = `{ "imports": {\n  "three": "./vendor/three/three.module.js",\n  "three/addons/": "./vendor/three/addons/"\n} }`;
  const next = html.replace(/\{\s*"imports":[\s\S]*?\}\s*\}/, map);
  if (next === html) throw new Error('could not find the import map to rewrite');
  return next;
}

/**
 * The public release folder: the same bundle, the thumbnails, and no models.
 *
 * `dist/spatial-ops-map-editor.html` on its own is a working editor, but it
 * resolves `assets/` next to itself, so opened alone it has no thumbnails and
 * no extra packs. That is fine for someone cloning the repository and wrong for
 * a release attachment, which has to be the whole thing in one download.
 */
export function packagePublic({ out } = {}) {
  const dest = out || join(ROOT, 'reference/opensource/spatial-ops-map-editor');
  const bundle = build();

  emptyDirectory(dest);
  mkdirSync(join(dest, 'assets/Prefabs'), { recursive: true });

  writeFileSync(join(dest, 'index.html'), readFileSync(bundle, 'utf8'), 'utf8');
  cpSync(join(ROOT, 'assets/Icons'), join(dest, 'assets/Icons'), { recursive: true });
  // The models are deliberately absent; the README that says so is not.
  cpSync(join(ROOT, 'assets/Prefabs/README.md'), join(dest, 'assets/Prefabs/README.md'));

  const packs = join(ROOT, 'packs');
  if (existsSync(packs)) cpSync(packs, join(dest, 'packs'), { recursive: true });
  for (const f of ['README.md', 'LICENSE', 'LICENCE']) {
    if (existsSync(join(ROOT, f))) cpSync(join(ROOT, f), join(dest, f));
  }
  writeFileSync(join(dest, 'HOW-TO-RUN.md'), PUBLIC_RUN, 'utf8');

  // The deliverable is the zip; the folder beside it is only what went into it,
  // kept so you can look before you upload.
  const zip = zipDirectory(dest, `${dest}.zip`);
  return { dest, zip };
}

const PUBLIC_RUN = `# Running this

Unzip anywhere, then serve the folder over HTTP and open it:

    npx serve .            # or: python -m http.server

then browse to the address it prints.

**It has to be served, not opened from disk.** Browsers refuse to fetch the
thumbnails and packs from a \`file://\` page, so double-clicking index.html gives
you an editor with no artwork. Any static server will do.

Objects are drawn as built-in stand-in shapes. To use the game's own models
instead, see \`assets/Prefabs/README.md\`.
`;

export function packageSelfHosted({ out, vendor = false } = {}) {
  const dest = out || join(ROOT, 'reference/selfhosted');

  // Always rebuild, so the package cannot be quietly older than src/.
  const bundle = build();

  emptyDirectory(dest);

  let html = readFileSync(bundle, 'utf8');
  if (vendor) html = vendorThree(html);
  writeFileSync(join(dest, 'index.html'), html, 'utf8');

  const staged = join(ROOT, 'assets');
  if (!existsSync(join(staged, 'Prefabs')) || readdirSync(join(staged, 'Prefabs')).length <= 1) {
    console.warn('assets/Prefabs is empty — run `npm run stage-assets` first, or this');
    console.warn('package will be the same as the public build.');
  }
  cpSync(staged, join(dest, 'assets'), { recursive: true });

  const packs = join(ROOT, 'packs');
  if (existsSync(packs)) cpSync(packs, join(dest, 'packs'), { recursive: true });

  writeFileSync(join(dest, 'Caddyfile'), CADDYFILE, 'utf8');
  writeFileSync(join(dest, 'README.md'), readme({ vendored: vendor }), 'utf8');

  return dest;
}

function main() {
  const args = process.argv.slice(2);
  const i = args.indexOf('--out');
  const out = i >= 0 && args[i + 1] ? join(ROOT, args[i + 1]) : null;
  const isPublic = args.includes('--public');
  const made = isPublic ? packagePublic({ out }) : { dest: packageSelfHosted({ out, vendor: args.includes('--vendor-three') }) };
  const dest = made.dest;

  const total = dirSize(dest);
  console.log(`Packaged ${dest}`);
  for (const part of ['assets/Icons', 'assets/Prefabs', 'packs']) {
    const s = dirSize(join(dest, part));
    if (s.files) console.log(`  ${part.padEnd(16)} ${String(s.files).padStart(4)} files  ${mb(s.total).padStart(9)}`);
  }
  console.log(`  ${'index.html'.padEnd(16)}    1 file   ${mb(statSync(join(dest, 'index.html')).size).padStart(9)}`);
  console.log(`  ${'total'.padEnd(16)} ${String(total.files).padStart(4)} files  ${mb(total.total).padStart(9)}`);
  if (isPublic) {
    console.log(`\nDeliverable  ${made.zip.file}`);
    console.log(`             ${made.zip.entries} entries, ${mb(made.zip.bytes)} — attach this to the release.`);
    console.log('The folder beside it is what went in, kept so you can look before uploading.');
  } else {
    console.log('\nNext: set a password hash in the Caddyfile, then `caddy.exe run --config Caddyfile`');
    console.log('from inside that folder. See its README.md.');
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
